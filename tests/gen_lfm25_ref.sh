#!/usr/bin/env bash
# tests/gen_lfm25_ref.sh - Regenerate the LFM2.5 oracle reference reproducibly.
#
# Writes, for MODE=dense (MODE=moe8 writes the same set under tests/ref_lfm25_moe8_128.*):
#   tests/ref_lfm25_dense_128.txt          greedy token IDs (one per line)
#   tests/ref_lfm25_dense_128.margins.txt  "<step> <top1> <top1-top2 logit margin>" per step
#   tests/ref_lfm25_dense_128.recipe       exact command, llama.cpp commit, model checksum
#
# Recipe: build/lfm25-llama-ref (tools/lfm25_llama_ref.c) = libllama, all layers on GPU,
# every token decoded as its own single-token batch, greedy argmax. Re-running this script on the
# same llama.cpp commit and model reproduces the files byte-for-byte; the recipe file records both.
set -euo pipefail

cd "$(dirname "$0")/.."

MODE="${1:-dense}"
N="${N:-128}"
PROMPT="${PROMPT:-Hello}"
LLAMA_DIR="${LLAMA_DIR:-/home/nii/workspace/llama.cpp}"
EXTRA_ARGS=()

if [ "$MODE" = "dense" ]; then
    MODEL_PATH="${MODEL_PATH:-/run/media/nii/pohjola/models/unsloth/LFM2.5-1.2B-Thinking-GGUF/LFM2.5-1.2B-Thinking-Q4_K_M.gguf}"
elif [ "$MODE" = "dense26" ]; then
    MODEL_PATH="${MODEL_PATH:-/run/media/nii/pohjola/models/LiquidAI/LFM2.5-2.6B/LFM2.5-2.6B-Q4_K_M.gguf}"
elif [ "$MODE" = "moe8" ]; then
    # LFM2.5-8B-A1B: 4.8 GiB, fully GPU-resident in llama.cpp too, so the same recipe applies.
    MODEL_PATH="${MODEL_PATH:-/run/media/nii/pohjola/models/LiquidAI/LFM2.5-8B-A1B-GGUF/LFM2.5-8B-A1B-Q4_K_M.gguf}"
elif [ "$MODE" = "moe" ]; then
    # LFM2.5-24B-A2B: 13.5 GiB does not fit 8 GB, so llama.cpp keeps the expert tensors on its CPU
    # backend (--cpu-experts); trunk, router and attention stay on the GPU.
    MODEL_PATH="${MODEL_PATH:-/run/media/nii/pohjola/models/LiquidAI/LFM2.5-24B-A2B-GGUF/LFM2.5-24B-A2B-Q4_K_M.gguf}"
    EXTRA_ARGS=(--cpu-experts)
else
    echo "Supported modes: dense (1.2B), dense26 (2.6B), moe8 (8B-A1B), moe (24B-A2B, experts on llama.cpp's CPU)." >&2
    exit 2
fi

REF_BIN="${REF_BIN:-./build/lfm25-llama-ref}"
[ -x "$REF_BIN" ] || { echo "Error: $REF_BIN missing; run: cmake --build build --target lfm25-llama-ref" >&2; exit 1; }
[ -f "$MODEL_PATH" ] || { echo "Error: model not found: $MODEL_PATH" >&2; exit 1; }

BASE="tests/ref_lfm25_${MODE}_${N}"
CMD=("$REF_BIN" --model "$MODEL_PATH" --prompt "$PROMPT" -n "$N"
     --tokens-out "$BASE.txt" --margins-out "$BASE.margins.txt" ${EXTRA_ARGS[@]+"${EXTRA_ARGS[@]}"})

echo "Generating $BASE.{txt,margins.txt} ..."
"${CMD[@]}" 2> /tmp/gen_lfm25_ref.log || { tail -20 /tmp/gen_lfm25_ref.log >&2; exit 1; }
PROMPT_LINE="$(grep '^prompt tokens' /tmp/gen_lfm25_ref.log)"
GPU="$(nvidia-smi --query-gpu=name,driver_version --format=csv,noheader 2>/dev/null)" || GPU="unknown (nvidia-smi unavailable)"

{
    echo "# Generated by tests/gen_lfm25_ref.sh $MODE on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
    echo "command:        ${CMD[*]}"
    echo "llama.cpp:      $(git -C "$LLAMA_DIR" rev-parse --short HEAD) ($(git -C "$LLAMA_DIR" log -1 --format=%s | cut -c1-60))"
    echo "model sha256:   $(sha256sum "$MODEL_PATH" | cut -d' ' -f1)"
    echo "$PROMPT_LINE"
    echo "gpu:            $GPU"
} > "$BASE.recipe"

echo "Done. $(wc -l < "$BASE.txt") tokens; smallest margins:"
sort -k3 -g "$BASE.margins.txt" | head -5 | sed 's/^/  step /'
